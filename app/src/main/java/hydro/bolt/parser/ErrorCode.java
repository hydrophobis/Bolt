package hydro.bolt.parser;

public enum ErrorCode {
    UNTERMINATED_STRING("E0001"),
    UNTERMINATED_CHAR("E0002"),
    UNTERMINATED_COMMENT("E0003"),
    INVALID_NUMBER("E0004"),
    UNEXPECTED_CHARACTER("E0005"),
    UNEXPECTED_TOKEN("E1001"),
    EXPECTED_TOKEN("E1002"),
    INTERFACE_NON_FUNCTION("E1003"),
    FORBIDDEN_HEADER("E1004"),
    MODULE_NOT_ANALYZED("W1005"),
    UNKNOWN_TYPE("E2001"),
    UNDEFINED_SYMBOL("E2002"),
    TYPE_MISMATCH("E2003"),
    ARGUMENT_COUNT_MISMATCH("E2004"),
    ARGUMENT_TYPE_MISMATCH("E2005"),
    UNKNOWN_MEMBER("E2006"),
    PRIVATE_MEMBER("E2007"),
    INTERFACE_NOT_IMPLEMENTED("E2008"),
    GENERIC_ARITY_MISMATCH("E2009"),
    MISSING_RETURN("E2010"),
    RETURN_TYPE_MISMATCH("E2011"),
    NOT_CALLABLE("E2012"),
    DUPLICATE_DECLARATION("E2013"),
    DELETE_NON_POINTER("E2014"),
    NO_HEAP_VIOLATION("E2015"),
    RECURSION_FORBIDDEN("E2016"),
    LAMBDAS_FORBIDDEN("E2017"),
    OPERATOR_OVERLOADING_FORBIDDEN("E2018"),
    UNKNOWN_CLASS("E2019"),
    INVALID_CONDITION("E2020"),
    BREAK_OUTSIDE_LOOP("E2021"),
    CONTINUE_OUTSIDE_LOOP("E2022"),
    SELF_OUTSIDE_METHOD("E2023"),
    UNREACHABLE_CODE("W2001"),
    UNUSED_VARIABLE("W2002"),
    IMPLICIT_NARROWING("W2003"),
    SHADOWED_DECLARATION("W2004"),
    UNKNOWN_CONFIG_KEY("W3001"),
    INVALID_CONFIG_VALUE("E3002"),
    MALFORMED_CONFIG_LINE("W3003"),
    UNSUPPORTED_C_STANDARD("E3004"),
    INTERNAL_ERROR("E9001");
    private final String id;

    ErrorCode(String id) {
        this.id = id;
    }

    public String id() {
        return id;
    }

    public boolean isWarning() {
        return id.charAt(0) == 'W';
    }
}
